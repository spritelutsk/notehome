  // ---------------- Terminal ----------------

  // Вкладка «Терминал» держит несколько независимых сессий. Серверу про вкладки знать не нужно:
  // каждое соединение с `/api/admin/terminal` и так порождает собственный PTY (server/terminal.js),
  // так что вся многовкладочность живёт здесь.
  //
  // Потолок стоит не от переполнения экрана: каждая вкладка — это настоящий процесс bash
  // на Raspberry Pi, и десяток забытых сессий там заметен.
  const MAX_TERMINAL_TABS = 8;

  function setTerminalStatus(text, cls) {
    el.terminalStatus.textContent = text;
    el.terminalStatus.className = 'terminal-status' + (cls ? ` ${cls}` : '');
  }

  // Строка статуса в шапке принадлежит активной вкладке. У остальных статус лежит в самой
  // сессии и выводится, когда на неё переключатся.
  function setSessionStatus(session, text, cls = '') {
    session.status = { text, cls };
    if (state.terminal.activeId === session.id) setTerminalStatus(text, cls);
    renderTerminalTabs();
  }

  function activeTerminalSession() {
    return state.terminal.sessions.find((s) => s.id === state.terminal.activeId) || null;
  }

  function ensureTerminal() {
    // Пустая вкладка «Терминал» бессмысленна: если сессий нет, открываем первую.
    if (state.terminal.sessions.length === 0) createTerminalSession();
    else fitActiveTerminal();
  }

  function fitActiveTerminal() {
    const session = activeTerminalSession();
    if (!session) return;
    // `fit()` по скрытому элементу меряет нулевую геометрию и портит раскладку, поэтому
    // подгоняем только видимую панель и только после того, как браузер её разложил.
    requestAnimationFrame(() => {
      if (el.viewTerminal.classList.contains('hidden')) return;
      try { session.fitAddon.fit(); } catch (_) { /* панель ещё не в потоке */ }
    });
  }

  function createTerminalSession() {
    const ts = state.terminal;
    if (ts.sessions.length >= MAX_TERMINAL_TABS) {
      toast(t('term_tab_limit_toast', { max: MAX_TERMINAL_TABS }), 'error');
      return null;
    }

    // Панель создаётся видимой, а соседние прячутся сразу же. Порядок принципиален:
    // `term.open()` меряет размер знакоместа по элементу, и на `display: none` получает нули —
    // терминал остаётся пустым даже после того, как панель покажут.
    const pane = document.createElement('div');
    pane.className = 'terminal-pane';
    ts.sessions.forEach((s) => s.pane.classList.add('hidden'));
    el.terminalPanes.appendChild(pane);

    const term = new Terminal({
      cursorBlink: true,
      fontSize: 14,
      fontFamily: "ui-monospace, 'SF Mono', 'DejaVu Sans Mono', Consolas, monospace",
      // Фон обязан совпадать с `.terminal-pane` в style.css: xterm красит только область
      // под знаками, и при расхождении по краям остаётся рамка чужого цвета.
      theme: { background: '#12151b', foreground: '#dfe3ea', cursor: '#dfe3ea', selectionBackground: '#33405a' },
    });
    const fitAddon = new FitAddon.FitAddon();
    term.loadAddon(fitAddon);
    term.open(pane);

    const session = {
      id: ts.nextId++,
      term,
      fitAddon,
      pane,
      ws: null,
      closing: false,
      status: { text: t('term_connecting'), cls: '' },
    };
    // Номер, а не готовая строка: название вкладки собирается при отрисовке, иначе после смены
    // языка уже открытые вкладки остались бы подписаны по-старому.
    session.n = session.id;
    ts.sessions.push(session);

    // Слушатели ввода вешаются один раз на сессию и смотрят на текущий сокет. Вешать их
    // внутри connectTerminalSocket() нельзя: xterm их не заменяет, а копит, и после
    // переподключения каждый нажатый символ уходил бы на сервер дважды.
    term.onData((data) => {
      if (session.ws && session.ws.readyState === WebSocket.OPEN) {
        session.ws.send(JSON.stringify({ type: 'input', data }));
      }
    });
    term.onResize(({ cols, rows }) => {
      if (session.ws && session.ws.readyState === WebSocket.OPEN) {
        session.ws.send(JSON.stringify({ type: 'resize', cols, rows }));
      }
    });

    connectTerminalSocket(session);
    activateTerminalSession(session.id);
    return session;
  }

  const sessionTitle = (session) => t('term_tab_title', { n: session.n });

  function activateTerminalSession(id) {
    const ts = state.terminal;
    const session = ts.sessions.find((s) => s.id === id);
    if (!session) return;
    ts.activeId = id;
    ts.sessions.forEach((s) => s.pane.classList.toggle('hidden', s.id !== id));
    setTerminalStatus(session.status.text, session.status.cls);
    renderTerminalTabs();
    fitActiveTerminal();
    if (!el.viewTerminal.classList.contains('hidden')) session.term.focus();
  }

  function closeTerminalSession(id) {
    const ts = state.terminal;
    const idx = ts.sessions.findIndex((s) => s.id === id);
    if (idx === -1) return;
    const session = ts.sessions[idx];

    // Закрытие сокета и есть завершение сессии: сервер убивает PTY по событию `close`.
    // Флаг нужен, чтобы обработчик `close` не дописал статус уже удалённой вкладке.
    session.closing = true;
    try { if (session.ws) session.ws.close(); } catch (_) { /* уже закрыт */ }
    session.term.dispose();
    session.pane.remove();
    ts.sessions.splice(idx, 1);

    if (ts.activeId !== id) { renderTerminalTabs(); return; }

    // Закрыли активную — переходим на соседнюю: сначала правую, иначе левую.
    const next = ts.sessions[idx] || ts.sessions[idx - 1];
    if (next) { activateTerminalSession(next.id); return; }
    ts.activeId = null;
    setTerminalStatus(t('term_no_sessions'));
    renderTerminalTabs();
  }

  // Вызывается при выходе из аккаунта. Иначе в той же вкладке браузера остались бы живые
  // сокеты и живые процессы bash на сервере, а следующий вошедший увидел бы в терминале
  // чужой вывод и чужую историю команд.
  function closeAllTerminalSessions() {
    // Копия массива обязательна: closeTerminalSession() делает splice по ходу перебора.
    [...state.terminal.sessions].forEach((s) => closeTerminalSession(s.id));
    state.terminal.nextId = 1; // нумерация вкладок начинается заново для следующего входа
  }

  function renderTerminalTabs() {
    const ts = state.terminal;
    el.terminalTabStrip.innerHTML = '';

    ts.sessions.forEach((session) => {
      const tab = document.createElement('div');
      tab.className = 'terminal-tab'
        + (session.id === ts.activeId ? ' active' : '')
        + (session.status.cls === 'error' ? ' dead' : '');

      const label = document.createElement('button');
      label.className = 'terminal-tab-label';
      label.textContent = sessionTitle(session);
      label.title = `${sessionTitle(session)} — ${session.status.text}`;
      label.addEventListener('click', () => activateTerminalSession(session.id));

      const close = document.createElement('button');
      close.className = 'terminal-tab-close';
      close.title = t('term_tab_close', { title: sessionTitle(session) });
      close.innerHTML = iconHtml('close');
      close.addEventListener('click', (e) => { e.stopPropagation(); closeTerminalSession(session.id); });

      tab.append(label, close);
      el.terminalTabStrip.appendChild(tab);
    });

    el.terminalAddBtn.disabled = ts.sessions.length >= MAX_TERMINAL_TABS;
    el.terminalAddBtn.title = el.terminalAddBtn.disabled
      ? t('term_tab_limit_title', { max: MAX_TERMINAL_TABS })
      : t('term_tab_new');
  }

  function connectTerminalSocket(session) {
    const proto = window.location.protocol === 'https:' ? 'wss:' : 'ws:';
    const ws = new WebSocket(`${proto}//${window.location.host}/api/admin/terminal`);
    session.ws = ws;
    setSessionStatus(session, t('term_connecting'));

    ws.addEventListener('open', () => {
      setSessionStatus(session, t('term_connected'), 'connected');
      if (state.terminal.activeId === session.id) fitActiveTerminal();
      ws.send(JSON.stringify({ type: 'resize', cols: session.term.cols, rows: session.term.rows }));
    });

    ws.addEventListener('message', (event) => {
      let msg;
      try { msg = JSON.parse(event.data); } catch (_) { return; }
      if (msg.type === 'data') session.term.write(msg.data);
      else if (msg.type === 'exit') setSessionStatus(session, t('term_exited', { code: msg.code }), 'error');
    });

    ws.addEventListener('close', () => {
      if (session.closing) return;
      // Переподключить эту же вкладку нельзя: в xterm остался вывод мёртвой сессии, а на
      // сервере PTY уже убит. Рабочий путь один — закрыть вкладку и открыть новую.
      if (session.status.cls !== 'error') {
        setSessionStatus(session, t('term_disconnected'), 'error');
      }
    });

    ws.addEventListener('error', () => {
      if (!session.closing) setSessionStatus(session, t('term_conn_error'), 'error');
    });
  }

