  async function deleteSelection() {
    const nodes = selectedNodes();
    if (!nodes.length) return;
    if (!confirm(t('confirm_delete_selection', { n: nodes.length }))) return;
    let deleted = 0;
    const failed = [];
    for (const node of nodes) {
      try {
        await api(`/api/nodes/${node.id}`, { method: 'DELETE' });
        deleted++;
      } catch (err) {
        failed.push(`${node.name}: ${err.message}`);
      }
    }
    if (deleted) toast(t('toast_trashed_n', { n: deleted }), 'success');
    if (failed.length) toast(failed[0], 'error');
    // Выделенная папка могла быть открытой — тогда возвращаемся к её родителю.
    if (state.selection.has(state.selectedFolderId)) {
      const gone = state.nodes.find((n) => n.id === state.selectedFolderId);
      state.selectedFolderId = gone ? gone.parentId : null;
    }
    clearSelection(false);
    await loadNodes();
  }

