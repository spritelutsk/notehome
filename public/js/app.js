  function formatBytes(bytes) {
    if (!bytes) return '0 ' + t('unit_b');
    const units = [t('unit_b'), t('unit_kb'), t('unit_mb'), t('unit_gb')];
    let i = 0, v = bytes;
    while (v >= 1024 && i < units.length - 1) { v /= 1024; i++; }
    return `${v.toFixed(v >= 10 || i === 0 ? 0 : 1)} ${units[i]}`;
  }

  function formatDate(str) {
    if (!str) return '';
    const d = new Date(str.replace(' ', 'T'));
    if (isNaN(d.getTime())) return str;
    return d.toLocaleString(DATE_LOCALE[state.settings.language] || DATE_LOCALE.uk, { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' });
  }

