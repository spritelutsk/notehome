  // корня удаления по определению не удалён, иначе строка была бы не корнем.

  // Дата без времени: «исчезнет» — это про день, а часы и минуты здесь только шумят.
  function formatDay(str) {
    if (!str) return '';
    const d = new Date(String(str).replace(' ', 'T'));
    if (isNaN(d.getTime())) return String(str);
    return d.toLocaleDateString(DATE_LOCALE[state.settings.language] || DATE_LOCALE.uk, {
      day: '2-digit', month: '2-digit', year: 'numeric',
    });
  }

