  function typingNow() {
    const a = document.activeElement;
    if (!a) return false;
    if (a.isContentEditable) return true;
    if (['INPUT', 'TEXTAREA', 'SELECT'].includes(a.tagName)) return true;
    // xterm держит фокус в собственной скрытой textarea, но подстраховаться дешевле.
    return !!a.closest('.terminal-pane, .xterm');
  }

