  // Строки дерева в том порядке, в каком они видны на экране: свёрнутые ветки в список
  // не попадают, поэтому стрелка вниз идёт ровно туда, куда ведёт глаз.
  const visibleTreeRows = () => [...el.treeRoot.querySelectorAll('.tree-row')];

  function moveFocus(list, current, delta) {
    if (!list.length) return;
    const at = list.indexOf(current);
    const next = at < 0 ? 0 : Math.min(list.length - 1, Math.max(0, at + delta));
    list[next].focus();
  }

  // Стрелки работают там, где сейчас фокус: в дереве — по строкам, на карточках — по сетке.
  // Если фокуса нет вообще, стрелка вниз заходит в дерево — иначе с клавиатуры не начать.
  function handleArrows(e) {
    const active = document.activeElement;
    const treeRow = active && active.closest && active.closest('.tree-row');
    const card = active && active.closest && active.closest('.item-card');

    if (treeRow) {
      const rows = visibleTreeRows();
      const id = Number(treeRow.dataset.id);
      if (e.key === 'ArrowDown') { e.preventDefault(); moveFocus(rows, treeRow, 1); return true; }
      if (e.key === 'ArrowUp') { e.preventDefault(); moveFocus(rows, treeRow, -1); return true; }
      if (e.key === 'ArrowRight') {
        e.preventDefault();
        if (foldersOf(id).length && !state.expanded.has(id)) {
          state.expanded.add(id);
          renderTree();
          // Перерисовка выбросила прежний узел из DOM — возвращаем фокус на ту же строку.
          const again = el.treeRoot.querySelector(`.tree-row[data-id="${id}"]`);
          if (again) again.focus();
        } else {
          moveFocus(visibleTreeRows(), treeRow, 1); // уже раскрыта — уходим на первого потомка
        }
        return true;
      }
      if (e.key === 'ArrowLeft') {
        e.preventDefault();
        if (state.expanded.has(id)) {
          state.expanded.delete(id);
          renderTree();
          const again = el.treeRoot.querySelector(`.tree-row[data-id="${id}"]`);
          if (again) again.focus();
        } else {
          // Свёрнутая папка — прыгаем к родителю: это то же движение «на уровень выше».
          const node = state.nodes.find((n) => n.id === id);
          const parentRow = node && node.parentId !== null
            && el.treeRoot.querySelector(`.tree-row[data-id="${node.parentId}"]`);
          if (parentRow) parentRow.focus();
        }
        return true;
      }
      return false;
    }

    if (card) {
      const cards = [...el.contentGrid.querySelectorAll('.item-card')];
      if (['ArrowRight', 'ArrowDown'].includes(e.key)) { e.preventDefault(); moveFocus(cards, card, 1); return true; }
      if (['ArrowLeft', 'ArrowUp'].includes(e.key)) { e.preventDefault(); moveFocus(cards, card, -1); return true; }
      return false;
    }

    if (e.key === 'ArrowDown' && state.view === 'explorer') {
      const rows = visibleTreeRows();
      if (rows.length) { e.preventDefault(); rows[0].focus(); return true; }
    }
    return false;
  }

  // Элемент, к которому относятся «редактировать» и «удалить»: то, на чём фокус,
  // иначе — единственная выделенная карточка.
  function focusedNode() {
    const active = document.activeElement;
    const holder = active && active.closest && active.closest('.item-card, .tree-row');
    if (holder) return state.nodes.find((n) => n.id === Number(holder.dataset.id)) || null;
    if (state.selection.size === 1) return selectedNodes()[0] || null;
    return null;
  }

  document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') {
      if (closeTopmostModal()) return;
      if (navOpen()) { setNav(false); return; }
      if (state.selection.size) { clearSelection(); return; }
      if (state.searchQuery.trim()) { clearSearch(); return; }
      return;
    }

    // Ctrl+K работает даже из поля ввода — это общепринятый способ «прыгнуть в поиск».
    if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 'k') {
      e.preventDefault();
      switchView('explorer');
      el.treeSearch.focus();
      el.treeSearch.select();
      return;
    }

    if (typingNow() || anyModalOpen()) return;
    if (e.ctrlKey || e.metaKey || e.altKey) return; // сочетания браузера не перехватываем
    if (!state.user) return;

    if (handleArrows(e)) return;
    if (state.view !== 'explorer' && !['?', '/'].includes(e.key)) return;

    const key = e.key;
    const inFolder = state.selectedFolderId !== null;

    // Создание: буква совпадает с типом (folder, link, text, doc) и работает только внутри
    // папки — в корне лежат лишь папки, там осмысленна одна `f`.
    const create = { f: 'folder', l: 'link', t: 'text', d: 'doc' }[key.toLowerCase()];
    if (create) {
      if (create === 'folder' && !inFolder) {
        e.preventDefault();
        openItemModal({ mode: 'create', type: 'folder', parentId: null });
        return;
      }
      if (!inFolder) return;
      e.preventDefault();
      openItemModal({ mode: 'create', type: create, parentId: state.selectedFolderId });
      return;
    }

    if (key === '/') { e.preventDefault(); el.treeSearch.focus(); el.treeSearch.select(); return; }
    if (key === '?') { e.preventDefault(); openHotkeys(); return; }

    if (key.toLowerCase() === 'e') {
      const node = focusedNode();
      if (!node) return;
      e.preventDefault();
      openItemModal({ mode: 'edit', type: node.type, nodeId: node.id });
      return;
    }

    if (key === 'Delete' || key === 'Backspace') {
      if (state.selection.size) { e.preventDefault(); deleteSelection(); return; }
      const node = focusedNode();
      if (!node) return;
      e.preventDefault();
      deleteNode(node);
    }
  });

