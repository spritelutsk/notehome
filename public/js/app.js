  // Карточки, строки дерева и хлебные крошки — это div и span с обработчиком клика. Такой
  // элемент не получает фокус табом, то есть с клавиатуры до него не добраться вообще,
  // а рамка `:focus-visible` в CSS никогда не срабатывает. Здесь мы возвращаем и то, и другое.
  function makeActivatable(node, onActivate) {
    node.tabIndex = 0;
    node.setAttribute('role', 'button');
    node.addEventListener('keydown', (e) => {
      // Внутри карточки и строки дерева лежит своя кнопка «три точки». События от неё всплывают
      // сюда, и без этой проверки Enter на кнопке гасился бы нашим preventDefault(), а вместо
      // меню открывался бы сам элемент — то есть меню было бы недоступно с клавиатуры.
      if (e.target !== node) return;
      if (e.key !== 'Enter' && e.key !== ' ') return;
      e.preventDefault();     // пробел иначе прокрутит страницу
      onActivate();
    });
  }

  // ---------------- Markdown ----------------
  //
  // Свой маленький рендерер вместо библиотеки: в проекте нет сборки, а тянуть в браузер
  // пакет ради заголовков и списков — несоразмерно.
  //
  // ГЛАВНОЕ ПРО БЕЗОПАСНОСТЬ. Текст страницы пишет пользователь, а результат уходит
  // в innerHTML. Порядок здесь не стилистический, а защитный:
  //   1) сначала экранируется ВЕСЬ исходный текст (`&`, `<`, `>`, `"`),
  //   2) и только потом по уже экранированной строке расставляются теги разметки.
  // После шага 1 в тексте физически не остаётся ни одного живого `<`, поэтому любой HTML,
  // который пользователь напишет руками, покажется как текст и выполниться не может.
  // Менять этот порядок местами нельзя ни при каких удобствах.
  //
  // Адреса ссылок проверяются отдельно: `[текст](javascript:…)` остаётся текстом, потому что
  // экранирование кавычек защищает от выхода из атрибута, но не от опасной схемы.

  const MD_SAFE_HREF = /^(?:https?:\/\/|mailto:)/i;

  function mdEscape(s) {
    return String(s)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }

  // Строчная разметка поверх уже экранированного текста.
  function mdInline(escaped) {
    // Код вынимается первым и возвращается последним: внутри него разметка не действует,
    // иначе `**` в примере кода превратилось бы в жирный шрифт.
    const codes = [];
    let s = escaped.replace(/`([^`\n]+)`/g, (_, code) => {
      codes.push(code);
      return `\u0001${codes.length - 1}\u0001`;
    });

    s = s.replace(/\[([^\]\n]+)\]\(([^)\s]+)\)/g, (whole, text, href) =>
      MD_SAFE_HREF.test(href)
        ? `<a href="${href}" target="_blank" rel="noopener noreferrer">${text}</a>`
        : whole // чужая схема (javascript:, data:) — оставляем как обычный текст
    );

    s = s.replace(/\*\*([^*\n]+)\*\*/g, '<b>$1</b>');
    s = s.replace(/(^|[^*])\*([^*\n]+)\*/g, '$1<i>$2</i>');

    return s.replace(/\u0001(\d+)\u0001/g, (_, i) => `<code>${codes[Number(i)]}</code>`);
  }

  // Блочная разметка. Возвращает готовый HTML — вызывающая сторона кладёт его в innerHTML.
  function renderMarkdown(src) {
    // \u0001 — служебный символ подстановки в mdInline; из пользовательского текста его надо
    // убрать, иначе им можно было бы подделать место вставки кода.
    const lines = String(src || '').replace(/[\u0000\u0001]/g, '').replace(/\r\n?/g, '\n').split('\n');
    const out = [];
    let para = [];
    let list = null; // { tag: 'ul' | 'ol', items: [] }
    let quote = [];

    const flushPara = () => {
      if (!para.length) return;
      // Одиночные переводы строк сохраняются как <br>, а не склеиваются, как велит канонический
      // markdown: это заметки, и человек, нажавший Enter, ждёт перевода строки.
      out.push(`<p>${para.map((l) => mdInline(mdEscape(l))).join('<br>')}</p>`);
      para = [];
    };
    const flushList = () => {
      if (!list) return;
      out.push(`<${list.tag}>${list.items.map((it) => `<li>${mdInline(mdEscape(it))}</li>`).join('')}</${list.tag}>`);
      list = null;
    };
    const flushQuote = () => {
      if (!quote.length) return;
      out.push(`<blockquote>${quote.map((l) => mdInline(mdEscape(l))).join('<br>')}</blockquote>`);
      quote = [];
    };
    const flushAll = () => { flushPara(); flushList(); flushQuote(); };

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];

      // Блок кода: всё до закрывающей ``` берётся как есть, только экранированным.
      const fence = /^\s*```(.*)$/.exec(line);
      if (fence) {
        flushAll();
        const body = [];
        i++;
        while (i < lines.length && !/^\s*```/.test(lines[i])) body.push(lines[i++]);
        out.push(`<pre><code>${mdEscape(body.join('\n'))}</code></pre>`);
        continue;
      }

      if (!line.trim()) { flushAll(); continue; }

      const heading = /^(#{1,6})\s+(.*)$/.exec(line);
      if (heading) {
        flushAll();
        const level = heading[1].length;
        out.push(`<h${level}>${mdInline(mdEscape(heading[2].trim()))}</h${level}>`);
        continue;
      }

      if (/^\s*(?:---+|\*\*\*+|___+)\s*$/.test(line)) { flushAll(); out.push('<hr>'); continue; }

      const quoted = /^\s*>\s?(.*)$/.exec(line);
      if (quoted) { flushPara(); flushList(); quote.push(quoted[1]); continue; }

      const bullet = /^\s*[-*+]\s+(.*)$/.exec(line);
      const numbered = /^\s*\d+[.)]\s+(.*)$/.exec(line);
      if (bullet || numbered) {
        flushPara(); flushQuote();
        const tag = bullet ? 'ul' : 'ol';
        if (!list || list.tag !== tag) { flushList(); list = { tag, items: [] }; }
        list.items.push((bullet || numbered)[1]);
        continue;
      }

      flushList(); flushQuote();
      para.push(line);
    }

    flushAll();
    return out.join('');
  }

