  const typeLabel = (type) => t(`help_type_${type}`);

  function renderTree() {
    el.treeRoot.innerHTML = '';
    const roots = foldersOf(null);
    if (roots.length === 0) {
      const hint = document.createElement('div');
      hint.className = 'empty-hint';
      hint.textContent = t('tree_empty');
      el.treeRoot.appendChild(hint);
      return;
    }
    roots.forEach((folder) => el.treeRoot.appendChild(renderTreeNode(folder, true)));
  }

  // `isRoot` отличает верхний уровень дерева от вложенного: корневая папка — точка входа в
  // раздел, поэтому её строка крупнее, со значком на подложке и счётчиком вложенного.
  function renderTreeNode(folder, isRoot = false) {
    const wrap = document.createElement('div');
    wrap.className = 'tree-node' + (isRoot ? ' is-root' : '');

    const row = document.createElement('div');
    row.className = 'tree-row'
      + (isRoot ? ' is-root' : '')
      + (state.selectedFolderId === folder.id ? ' selected' : '');
    row.dataset.id = folder.id;

    const subFolders = foldersOf(folder.id);
    const opened = subFolders.length > 0 && state.expanded.has(folder.id);
    const caret = document.createElement('span');
    caret.className = 'tree-caret' + (subFolders.length ? '' : ' empty');
    caret.innerHTML = subFolders.length ? iconHtml(opened ? 'chevronDown' : 'chevronRight') : '';
    caret.addEventListener('click', (e) => {
      e.stopPropagation();
      if (!subFolders.length) return;
      if (state.expanded.has(folder.id)) state.expanded.delete(folder.id);
      else state.expanded.add(folder.id);
      renderTree();
    });

    // Раскрытая папка получает открытый значок — то же различие, что и у галочки слева,
    // но читается с расстояния, на котором галочка уже сливается.
    const iconSvg = iconEl(opened ? 'folderOpen' : 'folder', 'tree-icon');
    let icon = iconSvg;
    if (isRoot) {
      icon = document.createElement('span');
      icon.className = 'tree-icon-tile';
      icon.appendChild(iconSvg);
    }

    const label = document.createElement('span');
    label.textContent = folder.name;
    label.style.overflow = 'hidden';
    label.style.textOverflow = 'ellipsis';
    label.style.minWidth = '0';

    const menuBtn = document.createElement('button');
    menuBtn.className = 'tree-menu-btn';
    menuBtn.innerHTML = iconHtml('dots');
    menuBtn.title = t('tree_menu_title');
    menuBtn.addEventListener('click', (e) => { e.stopPropagation(); openContextMenu(folder, e.clientX, e.clientY); });

    // Хвост строки: у корневой папки счётчик вложенного и кнопка меню делят одно место справа
    // (см. `.tree-tail` в style.css), у вложенной кнопка стоит в строке сама по себе.
    let tail = menuBtn;
    if (isRoot) {
      tail = document.createElement('span');
      tail.className = 'tree-tail';
      const count = childrenOf(folder.id).length;
      if (count) {
        const badge = document.createElement('span');
        badge.className = 'tree-count';
        badge.textContent = String(count);
        badge.title = t('tree_count_title', { count });
        tail.appendChild(badge);
      }
      tail.appendChild(menuBtn);
    }

    row.append(caret, icon, label, tail);
    makeActivatable(row, () => selectFolder(folder.id));
    row.addEventListener('click', () => selectFolder(folder.id));
    row.addEventListener('contextmenu', (e) => { e.preventDefault(); openContextMenu(folder, e.clientX, e.clientY); });

    row.draggable = true;
    attachDragSource(row, folder);
    attachDropTarget(row, folder.id);
    // Папка, над которой держат перетаскиваемое, разворачивается сама — иначе положить
    // что-либо в свёрнутую подпапку можно было бы только в два приёма.
    let hoverTimer = null;
    row.addEventListener('dragover', () => {
      if (hoverTimer || !subFolders.length || state.expanded.has(folder.id)) return;
      hoverTimer = setTimeout(() => { state.expanded.add(folder.id); renderTree(); }, 700);
    });
    row.addEventListener('dragleave', () => { clearTimeout(hoverTimer); hoverTimer = null; });
    row.addEventListener('drop', () => { clearTimeout(hoverTimer); hoverTimer = null; });

    wrap.appendChild(row);

    if (subFolders.length && state.expanded.has(folder.id)) {
      const childrenWrap = document.createElement('div');
      childrenWrap.className = 'tree-children';
      subFolders.forEach((sf) => childrenWrap.appendChild(renderTreeNode(sf)));
      wrap.appendChild(childrenWrap);
    }
    return wrap;
  }

  function expandPathTo(folderId) {
    let current = state.nodes.find((n) => n.id === folderId);
    while (current && current.parentId !== null) {
      state.expanded.add(current.parentId);
      current = state.nodes.find((n) => n.id === current.parentId);
    }
  }

  function selectFolder(folderId) {
    // Выбор папки и отбор — два разных режима правой части; открывая папку,
    // пользователь выходит из выборки, иначе клик по дереву не давал бы видимого результата.
    if (filterActive()) state.filter = { favorites: false };
    // Выделение живёт в пределах одной выборки: уходя из неё, оно теряет смысл и стало бы
    // невидимым — а групповое удаление всё равно сработало бы по нему.
    clearSelection(false);
    state.selectedFolderId = folderId;
    // Папка выбрана — на телефоне дерево закрывается само: иначе результат выбора
    // остался бы за выдвинутой панелью.
    setNav(false);
    expandPathTo(folderId);
    renderTree();
    renderContent();
  }

  function pathTo(folderId) {
    const path = [];
    let current = folderId === null ? null : state.nodes.find((n) => n.id === folderId);
    while (current) {
      path.unshift(current);
      current = current.parentId === null ? null : state.nodes.find((n) => n.id === current.parentId);
    }
    return path;
  }

