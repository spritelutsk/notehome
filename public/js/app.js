  // `box` и `overlay` передаются, потому что окон с запоминаемым размером теперь два:
  // окно правки и окно чтения текстовой страницы. Группа размера у них тоже разная,
  // так что растянутый редактор не перекраивает читалку и наоборот.
  function applyItemModalSize(group, box = el.itemModalBox) {
    let saved = null;
    try { saved = JSON.parse(localStorage.getItem(ITEM_MODAL_SIZE_PREFIX + group) || 'null'); } catch (_) { /* corrupt value */ }
    const size = saved && saved.width && saved.height ? saved : defaultItemModalSize(group);
    box.style.width = `${size.width}px`;
    box.style.height = `${size.height}px`;
  }

  // Persist the user's chosen modal size (via the CSS `resize` handle) so it's remembered
  // next time a modal of the same group is opened, including in future visits.
  const modalResizeObservers = new Map(); // box -> { observer, group }
  function watchItemModalSize(group, box = el.itemModalBox, overlay = el.itemOverlay) {
    const existing = modalResizeObservers.get(box);
    if (existing) { existing.group = group; return; }

    const entry = { group };
    entry.observer = new ResizeObserver(() => {
      if (overlay.classList.contains('hidden')) return;
      const { width, height } = box.getBoundingClientRect();
      localStorage.setItem(
        ITEM_MODAL_SIZE_PREFIX + entry.group,
        JSON.stringify({ width: Math.round(width), height: Math.round(height) })
      );
    });
    entry.observer.observe(box);
    modalResizeObservers.set(box, entry);
  }

