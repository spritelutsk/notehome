// Свой STUN/TURN (coturn на этой же машине) — то, без чего просмотр экрана работал только
// в пределах одной сети.
//
// Без STUN браузер собирает одни host-кандидаты, то есть собственные адреса машины. Двум
// сторонам в разных сетях они бесполезны: каждая видит адрес, до которого не дотянется.
// STUN сообщает браузеру, как его видно снаружи, — этого хватает, пока хотя бы один NAT
// не симметричный. Если симметричны оба (типичный мобильный интернет), прямого пути нет
// вовсе, и остаётся TURN: он не подсказывает адрес, а пропускает поток через себя.
//
// TURN включается отдельно и не просто так: через него видео идёт по домашнему каналу
// дважды — вверх от показывающего и вниз к смотрящему. Пока обе стороны дотягиваются
// напрямую, ретранслятор не используется, даже когда он объявлен: ICE берёт его последним.
//
// Чужой публичный STUN сюда не вписан намеренно: он сообщает адреса обоих участников
// третьей стороне, а выгода — только в случае «двое в разных сетях», ради которого и
// поднят свой.
const crypto = require('crypto');

// Адресов несколько по той же причине, что у CortenDesk: до одной машины ходят разными
// путями. Раздаются все заданные сразу, а не выбранный по адресу входа, — стороны могут
// прийти разными путями, и пусть каждая берёт тот, до которого дотянется. Недоступный
// адрес ICE просто отбросит по таймауту, соединение это не ломает.
const HOSTS = [
  ['lan', (process.env.TURN_HOST_LAN || '').trim()],
  ['vpn', (process.env.TURN_HOST_VPN || '').trim()],
  ['public', (process.env.TURN_HOST_PUBLIC || '').trim()],
].filter(([, host]) => host);

const PORT = Number(process.env.TURN_PORT || 3478) || 3478;
const SECRET = (process.env.TURN_SECRET || '').trim();
// Столько живёт выданный пароль. Сутки, а не минуты: реквизиты уходят клиенту в момент
// согласия, но вкладка может провисеть открытой и дольше, а перевыпуск на каждый сеанс
// потребовал бы лишнего обмена ровно там, где важна задержка.
const TTL_MS = (Number(process.env.TURN_TTL_HOURS || 24) || 24) * 3600 * 1000;

// Временный пароль по схеме, которую coturn понимает при `use-auth-secret`: имя — это срок
// годности и произвольная метка, пароль — HMAC-SHA1 от имени тем же секретом, что лежит
// в `static-auth-secret`. Постоянной пары логин-пароль нет вовсе: выданная протухает сама,
// и утечка из журнала браузера ничего не даёт через сутки.
function turnCredentials(now = Date.now()) {
  const username = `${Math.floor((now + TTL_MS) / 1000)}:spritenote`;
  const credential = crypto.createHmac('sha1', SECRET).update(username).digest('base64');
  return { username, credential };
}

// Пустой список означает «своего STUN нет»: клиент тогда соберёт одни host-кандидаты и
// покажет экран только в пределах одной сети. Это рабочее состояние, а не поломка, —
// поэтому здесь пусто, а не исключение.
function iceServers(now = Date.now()) {
  if (HOSTS.length === 0) return [];
  const out = HOSTS.map(([, host]) => ({ urls: `stun:${host}:${PORT}` }));
  if (!SECRET) return out;

  const { username, credential } = turnCredentials(now);
  HOSTS.forEach(([, host]) => {
    // Два транспорта: UDP — основной, TCP — запасной для сетей, где UDP режут целиком
    // (гостиничный Wi-Fi, корпоративные фильтры).
    out.push({
      urls: [`turn:${host}:${PORT}?transport=udp`, `turn:${host}:${PORT}?transport=tcp`],
      username,
      credential,
    });
  });
  return out;
}

module.exports = { iceServers, turnCredentials };
